"""Load and cache the deployed baseline model for each supported sport."""
from __future__ import annotations

from pathlib import Path
from typing import Mapping

from app.ml.features.engineer_multisport_features import FEATURE_COLUMNS
from app.ml.predict_multisport import load_trusted_baseline

SUPPORTED_SPORTS = frozenset({"NFL", "MLB", "EPL"})


class ModelRegistryError(RuntimeError):
    """Base error for model discovery and loading failures."""


class ModelNotFoundError(ModelRegistryError):
    """Raised when a deployed artifact cannot be found for a sport."""


class ModelConfigurationError(ModelRegistryError):
    """Raised when deployed artifacts are ambiguous or have invalid metadata."""


class ModelRegistry:
    """Resolve, verify, and cache one explicitly selected model per sport.

    The registry accepts explicit paths for production deployments. For local
    development and tests, :meth:`from_directory` discovers the immutable
    artifacts generated by the Sprint 2 training pipeline.
    """

    def __init__(self, artifact_paths: Mapping[str, Path | str]):
        normalized = {sport.upper(): Path(path) for sport, path in artifact_paths.items()}
        unsupported = set(normalized) - SUPPORTED_SPORTS
        if unsupported:
            raise ModelConfigurationError(
                f"Unsupported model configuration: {', '.join(sorted(unsupported))}"
            )
        self._artifact_paths = normalized
        self._cache: dict[str, tuple[object, dict]] = {}

    @classmethod
    def from_directory(cls, model_directory: Path | str) -> "ModelRegistry":
        """Discover exactly one versioned pipeline artifact for each sport.

        Refusing to guess when multiple versions exist keeps a deployment from
        silently changing models. In that case callers must pass explicit paths
        to ``ModelRegistry``.
        """
        root = Path(model_directory)
        paths: dict[str, Path] = {}
        for sport in sorted(SUPPORTED_SPORTS):
            direct_path = root / f"{sport.lower()}_baseline.pkl"
            candidates = ([direct_path] if direct_path.is_file() else []) + sorted(
                root.glob(f"{sport.lower()}-*/{sport.lower()}_baseline.pkl")
            )
            if not candidates:
                raise ModelNotFoundError(f"No deployed model found for {sport} in {root}")
            if len(candidates) > 1:
                raise ModelConfigurationError(
                    f"Multiple deployed models found for {sport}; select an explicit artifact path"
                )
            paths[sport] = candidates[0]
        return cls(paths)

    def get(self, sport: str):
        """Return the cached ``(model, metadata)`` pair for ``sport``."""
        normalized_sport = sport.strip().upper()
        if normalized_sport not in SUPPORTED_SPORTS:
            raise ModelConfigurationError(f"Unsupported sport: {sport}")
        if normalized_sport in self._cache:
            return self._cache[normalized_sport]

        artifact_path = self._artifact_paths.get(normalized_sport)
        if artifact_path is None or not artifact_path.is_file():
            raise ModelNotFoundError(f"No deployed model configured for {normalized_sport}")

        try:
            model, metadata = load_trusted_baseline(artifact_path)
        except (OSError, ValueError, KeyError) as exc:
            raise ModelConfigurationError(
                f"Could not load the configured {normalized_sport} model: {exc}"
            ) from exc
        self._validate_metadata(normalized_sport, metadata)
        self._cache[normalized_sport] = (model, metadata)
        return self._cache[normalized_sport]

    def load_all(self) -> dict[str, tuple[object, dict]]:
        """Load every supported model, failing if any deployment is invalid."""
        return {sport: self.get(sport) for sport in sorted(SUPPORTED_SPORTS)}

    @staticmethod
    def _validate_metadata(sport: str, metadata: dict) -> None:
        if metadata.get("sport", "").upper() != sport:
            raise ModelConfigurationError(
                f"Configured {sport} artifact contains {metadata.get('sport')!r} metadata"
            )
        if metadata.get("feature_columns") != FEATURE_COLUMNS:
            raise ModelConfigurationError(f"Configured {sport} model has an incompatible feature schema")
        if metadata.get("classes") != [0, 1]:
            raise ModelConfigurationError(f"Configured {sport} model has incompatible classes")
