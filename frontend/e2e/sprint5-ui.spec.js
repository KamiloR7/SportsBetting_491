test('Scenario 4 / SCRUM-227 desktop unavailable API and successful recovery', async ({ page }, testInfo) => {
  const unexpected = await mockApi(page, { listMode: 'error' })
  await page.goto('/dashboard?league=football&status=scheduled')
  await expect(page.getByRole('alert')).toContainText('Match data is unavailable.')
  await expect(page.getByRole('button', { name: /Football/ })).toBeEnabled()
  await evidence(page, testInfo, 'unavailable-api')
  await page.unroute('**/api/**')
  const recovery = await mockApi(page)
  await page.reload()
  await expect(page.getByRole('button', { name: /Cincinnati Bengals 1.60 Bet/ })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect([...unexpected, ...recovery]).toEqual([])
})

